def _select_top_vs_bottom_group_row(hr_df: pd.DataFrame) -> pd.Series | None:
    if hr_df is None or hr_df.empty:
        return None
    idx = hr_df.index.astype(str)
    # Prefer the explicit highest-group contrast (e.g., pct_group_P>75).
    gt_mask = idx.str.contains(r"P>", regex=True)
    if gt_mask.any():
        return hr_df.loc[gt_mask].iloc[-1]
    # Otherwise prefer the last percentile-group dummy if present.
    pct_mask = idx.str.contains(r"pct_group", regex=True)
    if pct_mask.any():
        return hr_df.loc[pct_mask].iloc[-1]
    # Final fallback: use the last row.
    return hr_df.iloc[-1]



