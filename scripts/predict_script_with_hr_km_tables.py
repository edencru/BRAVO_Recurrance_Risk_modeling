def main():
    args = get_args()

    model_output_dir = args.model_output_dir
    prediction_output_dir = args.prediction_output_dir or args.model_output_dir
    sample_ids = _load_sample_ids(args.predict_ids_csv)
    plot_style = _build_plot_style(args)
    raw_blocks = [b.strip() for b in str(args.predict_blocks).split(",") if b.strip()]

    # Resolve ANY the same way as predict_concat_only
    models_dir_main = os.path.join(model_output_dir, args.subtype, "cv_models")
    discovered_any = []
    if os.path.isdir(models_dir_main):
        for fname in sorted(os.listdir(models_dir_main)):
            if fname.endswith(".pkl"):
                stem = os.path.splitext(fname)[0]
                if stem.startswith("ALL__"):
                    discovered_any.append(stem)

    req_blocks = []
    for b in raw_blocks:
        bu = b.upper()
        if bu == "ANY":
            req_blocks.extend(discovered_any)
        elif b.startswith("ALL__"):
            req_blocks.append(b)
        else:
            req_blocks.append(bu)

    _seen = set()
    req_blocks = [b for b in req_blocks if not (b in _seen or _seen.add(b))]
    pcts, pct_key = _parse_percentiles(args.percentiles)
    token = (pct_key if pct_key else str(args.percentiles)).replace(",", "-")

    print("🚀 Prediction run configuration")
    print(f"   model_output_dir       : {model_output_dir}")
    print(f"   prediction_output_dir  : {prediction_output_dir}")
    print(f"   subtype                : {args.subtype}")
    print(f"   predict_matrix_csv     : {args.predict_matrix_csv}")
    print(f"   predict_labels_csv     : {args.predict_labels_csv}")
    print(f"   predict_ids_csv        : {args.predict_ids_csv}")
    print(f"   percentiles            : {args.percentiles}")
    print(f"   scale_mode             : {args.scale_mode}")
    print(f"   predict_blocks         : {args.predict_blocks}")
    print(f"   predict_stacked        : {args.predict_stacked}")
    print(f"   legend_mode            : {plot_style['legend_mode']}")
    print(f"   km_show_ci             : {plot_style['km_show_ci']}")
    print(f"   km_ci_alpha            : {plot_style['km_ci_alpha']}")
    print(f"   km_figsize             : {plot_style['km_figsize']}")
    print(f"   km_linewidth           : {plot_style['km_linewidth']}")
    print(f"   hr_figsize             : {plot_style['hr_figsize']}")
    print(f"   hr_compare_figsize     : {plot_style['hr_compare_figsize']}")
    print(f"   finalHR                : {args.finalHR}")
    print(f"   finalhr_row_height     : {plot_style['finalhr_row_height']}")
    print(f"   finalhr_height_padding : {plot_style['finalhr_height_padding']}")
    print(f"   finalhr_min_height     : {plot_style['finalhr_min_height']}")

    if req_blocks:
        print("🔮 Predicting with per-block / ALL models ...")
        predict_concat_only(
            model_output_dir=model_output_dir,
            prediction_output_dir=prediction_output_dir,
            subtype=args.subtype,
            pred_matrix_csv=args.predict_matrix_csv,
            sample_ids=sample_ids,
            pred_labels_csv=args.predict_labels_csv,
            percentiles=args.percentiles,
            scale_mode=args.scale_mode,
            blocks=args.predict_blocks,
            plot_style=plot_style,
        )

    model_order = list(req_blocks)
    if args.predict_stacked:
        print("🔮 Predicting with STACKED_FINAL.pkl ...")
        predict_stacked(
            model_output_dir=model_output_dir,
            prediction_output_dir=prediction_output_dir,
            subtype=args.subtype,
            pred_matrix_csv=args.predict_matrix_csv,
            sample_ids=sample_ids,
            pred_labels_csv=args.predict_labels_csv,
            percentiles=args.percentiles,
            scale_mode=args.scale_mode,
            plot_style=plot_style,
        )
        model_order.append("STACKED")

    path_info = _resolve_prediction_dirs(
        model_output_dir=model_output_dir,
        prediction_output_dir=prediction_output_dir,
        subtype=args.subtype,
        pred_labels_csv=args.predict_labels_csv,
    )
    _plot_combined_model_hr_from_saved(
        preds_dir=path_info["preds_dir"],
        plots_dir=path_info["plots_dir"],
        token=token,
        model_order=model_order,
        style=plot_style,
    )
    _plot_combined_model_group_hr_from_saved(
        preds_dir=path_info["preds_dir"],
        plots_dir=path_info["plots_dir"],
        token=token,
        model_order=model_order,
        style=plot_style,
    )
    _plot_combined_model_roc_from_saved(
        preds_dir=path_info["preds_dir"],
        plots_dir=path_info["plots_dir"],
        token=token,
        model_order=model_order,
        style=plot_style,
        pred_labels_csv=args.predict_labels_csv,
        subtype=args.subtype,
    )

    finalhr_models = _resolve_requested_models(
        [x.strip() for x in str(args.finalHR).split(",") if x.strip()] if args.finalHR else [],
        model_order,
    )
    if args.finalHR:
        print(f"[INFO] finalHR requested: {args.finalHR}")
        print(f"[INFO] finalHR resolved models: {finalhr_models}")
    if finalhr_models:
        _plot_combined_model_hr_from_saved(
            preds_dir=path_info["preds_dir"],
            plots_dir=path_info["plots_dir"],
            token=token,
            model_order=finalhr_models,
            style=plot_style,
            out_prefix="FINALHR",
            title="Continuous hazard ratio comparison (finalHR)",
        )
        _plot_combined_model_group_hr_from_saved(
            preds_dir=path_info["preds_dir"],
            plots_dir=path_info["plots_dir"],
            token=token,
            model_order=finalhr_models,
            style=plot_style,
            out_prefix="FINALHR",
            title="Binary top-vs-bottom hazard ratio comparison (finalHR)",
        )
    elif args.finalHR:
        print("[INFO] finalHR plots skipped: none of the requested models matched the available predicted models.")

    print("✅ Done.")


