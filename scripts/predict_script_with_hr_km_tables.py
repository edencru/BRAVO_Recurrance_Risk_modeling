def _nice_time_ticks(max_time, n_ticks=6):
    try:
        max_time = float(max_time)
    except Exception:
        return np.array([0.0])
    if not np.isfinite(max_time) or max_time <= 0:
        return np.array([0.0])
    ticks = np.linspace(0.0, max_time, int(max(2, n_ticks)))
    if max_time >= 20:
        ticks = np.round(ticks).astype(float)
    elif max_time >= 5:
        ticks = np.round(ticks, 1)
    else:
        ticks = np.round(ticks, 2)
    ticks = np.unique(ticks)
    if ticks[0] != 0:
        ticks = np.insert(ticks, 0, 0.0)
    return ticks


def _build_km_table_long(df, time_col, event_col, group_col, labels, n_ticks=6):
    rows = []
    max_time = pd.to_numeric(df[time_col], errors='coerce').max()
    ticks = _nice_time_ticks(max_time, n_ticks=n_ticks)
    for lab in labels:
        dd = df[df[group_col] == lab].copy()
        if dd.empty:
            continue
        t = pd.to_numeric(dd[time_col], errors='coerce')
        e = pd.to_numeric(dd[event_col], errors='coerce').fillna(0).astype(int)
        ok = (~t.isna()) & (~e.isna())
        t = t[ok]
        e = e[ok]
        if len(t) == 0:
            continue
        for tick in ticks:
            rows.append({"group": lab, "metric": "At risk", "time": float(tick), "value": int((t >= tick).sum())})
            rows.append({"group": lab, "metric": "Events", "time": float(tick), "value": int(((t <= tick) & (e == 1)).sum())})
            rows.append({"group": lab, "metric": "Censored", "time": float(tick), "value": int(((t <= tick) & (e == 0)).sum())})
    return pd.DataFrame(rows)


def _save_km_table_outputs(df, time_col, event_col, group_col, labels, out_png, title=None, n_ticks=6):
    km_long = _build_km_table_long(df, time_col, event_col, group_col, labels, n_ticks=n_ticks)
    if km_long.empty:
        return
    km_long.to_csv(_table_csv_path(out_png, suffix='__risk_table'), index=False)
    row_labels = []
    wide_rows = []
    times = sorted(km_long['time'].unique().tolist())
    for lab in labels:
        for metric in ["At risk", "Events", "Censored"]:
            sub = km_long[(km_long['group'] == lab) & (km_long['metric'] == metric)].sort_values('time')
            if sub.empty:
                continue
            row_labels.append(f"{lab} | {metric}")
            wide_rows.append(sub['value'].astype(int).tolist())
    if not wide_rows:
        return
    wide_df = pd.DataFrame(wide_rows, columns=[str(t) for t in times])
    wide_df.insert(0, 'Row', row_labels)
    wide_df.to_csv(_table_csv_path(out_png, suffix='__risk_table_wide'), index=False)
    _save_dataframe_table_plot(wide_df, _table_plot_path(out_png, suffix='__risk_table'), title=title or 'KM risk/event table', fontsize=8, col_width_scale=1.05)


def _build_hr_table_df(summary_df):
    plot_df = _summary_to_hr_frame(summary_df)
    if plot_df.empty:
        return pd.DataFrame()
    original = summary_df.copy()
    out = pd.DataFrame(index=plot_df.index)
    out['Term'] = plot_df.index.astype(str)
    out['HR'] = plot_df['HR'].map(_format_num)
    out['CI_low'] = plot_df['HR_lo'].map(_format_num)
    out['CI_high'] = plot_df['HR_hi'].map(_format_num)
    out['95% CI'] = [f"{_format_num(lo)}–{_format_num(hi)}" for lo, hi in zip(plot_df['HR_lo'], plot_df['HR_hi'])]
    out['p'] = plot_df['p'].map(_format_p_value)
    for col in ['n_used', 'n_events', 'unit', 'reference_group', 'comparison_group', 'reference_n', 'comparison_n']:
        if col in original.columns:
            vals = original.loc[out.index, col]
            out[col] = vals.values
    return out.reset_index(drop=True)


