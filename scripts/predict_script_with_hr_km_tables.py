def _norm_color_key(key):
    s = str(key).strip().lower()
    s = re.sub(r"\s+", "", s)
    return s


def _parse_color_map(spec):
    out = {}
    if not spec:
        return out
    raw = str(spec).strip()
    if not raw:
        return out
    for part in raw.split(","):
        piece = part.strip()
        if not piece:
            continue
        if "=" not in piece:
            raise ValueError(f"Color map entry must look like key=#HEX. Bad entry: {piece}")
        k, v = piece.split("=", 1)
        out[_norm_color_key(k)] = v.strip()
    return out


def _parse_figsize(spec, default=None):
    if spec is None:
        return default
    raw = str(spec).strip().lower()
    if raw in ("", "none", "auto"):
        return default
    for sep in ("x", ","):
        if sep in raw:
            parts = [p.strip() for p in raw.split(sep)]
            if len(parts) == 2:
                try:
                    w = float(parts[0]); h = float(parts[1])
                    if w > 0 and h > 0:
                        return (w, h)
                except Exception:
                    pass
    raise ValueError(f"Figure size must look like '8,5' or '8x5'. Got: {spec}")

def _row_sized_figsize(base_figsize, n_rows, row_height=0.42, height_padding=0.55, min_height=0.0, default_width=8.0, default_height=1.4):
    if base_figsize is None:
        width = float(default_width)
    else:
        width = float(base_figsize[0])
    n_rows = max(int(n_rows), 1)
    height = max(float(min_height), float(row_height) * n_rows + float(height_padding))
    return (width, height)


def _resolve_requested_models(requested_models, available_models):
    requested = [str(x).strip() for x in (requested_models or []) if str(x).strip()]
    available = [str(x) for x in (available_models or [])]
    if not requested:
        return []

    lookup = {str(a).upper(): str(a) for a in available}
    if "STACKED" in lookup:
        lookup.setdefault("STACK", lookup["STACKED"])
    resolved = []
    seen = set()
    for item in requested:
        key = str(item).upper()
        match = lookup.get(key)
        if match is None:
            continue
        if match in seen:
            continue
        seen.add(match)
        resolved.append(match)
    return resolved


