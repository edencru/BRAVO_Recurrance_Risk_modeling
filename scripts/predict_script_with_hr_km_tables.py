def _save_legend_only(handles, labels, out_png, title=None, ncol=1):
    if not handles or not labels:
        return
    n = len(labels)
    fig_w = max(3.0, min(10.0, 1.6 * max(1, ncol)))
    fig_h = max(1.4, 0.55 * np.ceil(n / max(1, ncol)) + 0.8)
    fig = plt.figure(figsize=(fig_w, fig_h))
    ax = fig.add_subplot(111)
    ax.axis("off")
    leg = ax.legend(
        handles,
        labels,
        loc="center",
        frameon=False,
        ncol=ncol,
        title=title,
        handlelength=2.2,
        columnspacing=1.2,
    )
    fig.canvas.draw()
    bbox = leg.get_window_extent(fig.canvas.get_renderer()).transformed(fig.dpi_scale_trans.inverted())
    fig.savefig(out_png, dpi=200, bbox_inches=bbox.expanded(1.08, 1.15))
    plt.close(fig)


def _finalize_legend(ax, handles, labels, plot_path, style, loc="best", ncol=1, title=None):
    existing = ax.get_legend()
    if existing is not None:
        existing.remove()
    if not handles or not labels:
        return
    mode = str(style.get("legend_mode", "separate")).lower()
    if mode in ("embedded", "both"):
        ax.legend(handles=handles, labels=labels, loc=loc, frameon=False, ncol=ncol, title=title)
    if mode in ("separate", "both"):
        _save_legend_only(handles, labels, _legend_path(plot_path), title=title, ncol=ncol)


def _build_labels_map_from_df(df, sample_ids_series, sid_col=None):
    labels_map = {}
    if df is None or df.empty:
        return labels_map

    cols_lower = {c.lower(): c for c in df.columns}
    sid = sid_col or _pick_col(cols_lower, "sample_id") or df.columns[0]
    idxed = df.set_index(sid)
    cols_lower = {c.lower(): c for c in idxed.columns}

    ds_col = _pick_col(cols_lower, "disease_status", "label", "y_label")
    if ds_col:
        labels_map["disease_status"] = (
            idxed[ds_col].astype(str).str.strip().str.lower().reindex(sample_ids_series.values)
        )

    ev_col = _pick_col(cols_lower, "event_observed", "dfs_event", "os_event", "event")
    if ev_col:
        labels_map["event_observed"] = (
            pd.to_numeric(idxed[ev_col], errors="coerce").reindex(sample_ids_series.values)
        )

    te_col = _pick_col(cols_lower, "time_to_event", "dfs_months", "os_months", "time")
    if te_col:
        labels_map["time_to_event"] = (
            pd.to_numeric(idxed[te_col], errors="coerce").reindex(sample_ids_series.values)
        )

    return labels_map


