def _format_p_value(v):
    try:
        v = float(v)
    except Exception:
        return ""
    if np.isnan(v):
        return ""
    if v < 1e-16:
        return "<1e-16"
    return f"{v:.2e}"


def _format_num(v, digits=3):
    try:
        v = float(v)
    except Exception:
        return ""
    if np.isnan(v):
        return ""
    return f"{v:.{digits}f}"


