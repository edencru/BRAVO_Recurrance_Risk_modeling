"""
Prediction and validation-output plotting script.

This script applies previously trained recurrence-risk models to a prepared prediction
matrix. It is intended to be used after the final training script has saved model
artifacts and after the validation-processing script has generated a validation matrix
with feature names matching the trained model schema.

Its purpose is to load saved block-level, ALL, and/or
stacked models; align the prediction matrix to the saved training feature schema;
generate predicted recurrence-risk probabilities; and produce prediction diagnostics,
survival plots, and summary outputs when labels are available.

Overall workflow:

1. Load trained model artifacts from the final model output directory.
2. Load the saved preprocessing artifacts and feature-order files.
3. Read a prepared prediction matrix, usually generated by the validation-processing
   script.
4. Normalize sample IDs and align prediction features to the exact training feature
   order expected by each model.
5. Apply the saved preprocessing/scaling objects when required.
6. Generate predicted recurrence-risk probabilities for requested models.
7. Save prediction tables for each model.
8. If labels or survival annotations are provided, generate ROC, histogram,
   Kaplan-Meier, event-rate, and Cox/hazard-ratio diagnostic plots.
9. Optionally compare predictions across multiple models in combined summary plots.

Input requirements:
The prediction matrix should already contain model-ready features using the same
feature prefixes and naming convention used during training:

* RNAblock__
* CNVblock__
* MUTblock__
* CLINICALblock__

This script expects the prediction matrix to contain the selected features required
by the trained model. Missing features can be aligned or zero-filled according to the
saved training schema, but feature generation itself should be performed upstream by
the validation-processing workflow.

Model artifacts:
Model artifacts are loaded from:
<model_output_dir>/<subtype>/cv_models
<model_output_dir>/<subtype>/preprocessing

Supported model types include:

* RNA block model
* CNV block model
* MUT block model
* CLINICAL block model
* ALL combined multi-block model
* STACKED ensemble model

The script keeps minimal custom classes, including RecurrentOverSampler and
BlockPreprocessor, so previously saved sklearn/imblearn pipeline objects can be
unpickled and used for prediction.

Prediction outputs:
Prediction outputs are written to:
<prediction_output_dir>/<labels-file-stem>/predictions
<prediction_output_dir>/<labels-file-stem>/plots

If prediction_output_dir is not provided, outputs are written under model_output_dir.
When no labels file is provided, the subtype name is used as the prediction run name.

Saved prediction files may include:

* per-model predicted probabilities
* percentile/risk-group assignments
* combined model prediction summaries
* prediction diagnostics and feature-alignment checks
* ROC statistics when recurrence labels are available
* Cox model summaries when survival time/event data are available

Label and survival support:
If a prediction labels file is supplied, the script can use recurrence status and/or
survival information to evaluate predictions. Supported diagnostics include:

* ROC curves and AUC
* prediction histograms stratified by label or risk group
* Kaplan-Meier curves by predicted-risk percentile groups
* event-rate bar plots
* continuous Cox models using predicted score
* Cox models comparing percentile risk groups
* top-vs-bottom group hazard-ratio comparisons

Plotting:
The script includes plotting utilities for individual models and combined model
comparisons. Plot colors, legend behavior, confidence interval shading, figure sizes,
percentile cut points, and other display options can be controlled from the command
line. Legends and statistical summaries can also be saved as separate files for figure
assembly.

STACKED ensemble model prediction:
For STACKED models, the script loads the saved stacked model and required block-level
preprocessing behavior. The stacked model combines block-level predictions using the
trained meta-model and outputs a final stacked recurrence-risk probability.

"""


