def _prepare_prediction_matrix(pred_matrix_csv, pred_labels_csv, subtype, sample_ids=None):
    X = pd.read_csv(pred_matrix_csv, index_col=0)
    X.index = _norm_ids(X.index)
    X.columns = X.columns.astype(str).str.strip()

    labels_df = None
    sid_col = None
    label_ids = None
    if pred_labels_csv is not None and os.path.exists(pred_labels_csv):
        labels_df = pd.read_csv(pred_labels_csv)
        labels_df = _filter_labels_to_subtype(labels_df, subtype)
        cols_lower = {c.lower(): c for c in labels_df.columns}
        sid_col = _pick_col(cols_lower, "sample_id") or labels_df.columns[0]
        label_ids = _norm_ids(labels_df[sid_col])

    sample_ids_norm = _norm_ids(sample_ids) if sample_ids is not None else None

    if label_ids is not None:
        keep = [s for s in label_ids if s in X.index]
        if sample_ids_norm is not None:
            keep_set = set(sample_ids_norm)
            keep = [s for s in keep if s in keep_set]
    elif sample_ids_norm is not None:
        keep = [s for s in sample_ids_norm if s in X.index]
    else:
        keep = list(X.index)

    X = X.reindex(keep)
    if X.shape[0] == 0:
        raise ValueError("After subsetting to label/sample IDs, no samples remain.")

    X = X.apply(pd.to_numeric, errors="coerce").replace([np.inf, -np.inf], np.nan).fillna(0.0)
    return X, labels_df, sid_col


