def _plot_km(df, time_col, event_col, group_col, labels, title, out_png, style, extra_text=""):
    try:
        from lifelines import KaplanMeierFitter
        from lifelines.statistics import logrank_test, multivariate_logrank_test
    except Exception:
        print("[KM] lifelines not available; skipping KM.")
        return

    _save_km_table_outputs(
        df=df,
        time_col=time_col,
        event_col=event_col,
        group_col=group_col,
        labels=labels,
        out_png=out_png,
        title=f"{title} — risk/event table",
        n_ticks=int(style.get("km_table_n_ticks", 6)),
    )

    plt.figure(figsize=tuple(style.get("km_figsize", (6.8, 4.6))))
    ax = plt.gca()
    present = []
    legend_handles = []
    color_map = _group_color_dict(labels, style)
    km = KaplanMeierFitter()
    km_lw = float(style.get("km_linewidth", 2.0))

    for lab in labels:
        dd = df[df[group_col] == lab]
        if dd.empty:
            continue
        present.append(lab)
        color = color_map[lab]
        km.fit(dd[time_col].astype(float).values, dd[event_col].astype(int).values, label=lab)
        km.plot(
            ax=ax,
            ci_show=bool(style.get("km_show_ci", False)),
            ci_alpha=float(style.get("km_ci_alpha", 0.20)),
            color=color,
            linewidth=km_lw,
        )
        legend_handles.append(Line2D([0], [0], color=color, lw=km_lw, label=lab))

    ptxt = ""
    try:
        if len(present) >= 2:
            if len(present) == 2:
                a_lab, b_lab = present[:2]
                a_df = df[df[group_col] == a_lab]
                b_df = df[df[group_col] == b_lab]
                res = logrank_test(
                    a_df[time_col].astype(float),
                    b_df[time_col].astype(float),
                    event_observed_A=a_df[event_col].astype(int),
                    event_observed_B=b_df[event_col].astype(int),
                )
                ptxt = f"Log-rank p ({a_lab} vs {b_lab}): {('<1e-16' if res.p_value < 1e-16 else f'{res.p_value:.2e}') }"
            else:
                glob = multivariate_logrank_test(
                    df[time_col].astype(float), df[group_col], df[event_col].astype(int)
                )
                ptxt = f"Global p: {('<1e-16' if glob.p_value < 1e-16 else f'{glob.p_value:.2e}') }"
    except Exception as e:
        print(f"[KM] p-value calc failed: {e}")

    ax.set_title(title)
    ax.set_xlabel("Time")
    ax.set_ylabel("Survival probability")
    ax.set_ylim(0, 1)
    _save_stats_figure(out_png, (extra_text + ("\n" if extra_text and ptxt else "") + ptxt).strip())
    _finalize_legend(ax, legend_handles, [h.get_label() for h in legend_handles], out_png, style, loc="best")
    plt.tight_layout()
    plt.savefig(out_png, dpi=200)
    plt.close()


def _summary_to_hr_frame(summary_df):
    if summary_df is None or summary_df.empty:
        return pd.DataFrame()

    plot_df = summary_df.copy().replace([np.inf, -np.inf], np.nan)

    if "exp(coef)" in plot_df.columns:
        plot_df["HR"] = pd.to_numeric(plot_df["exp(coef)"], errors="coerce")
    else:
        plot_df["HR"] = np.exp(pd.to_numeric(plot_df["coef"], errors="coerce"))

    if "exp(coef) lower 95%" in plot_df.columns:
        plot_df["HR_lo"] = pd.to_numeric(plot_df["exp(coef) lower 95%"], errors="coerce")
        plot_df["HR_hi"] = pd.to_numeric(plot_df["exp(coef) upper 95%"], errors="coerce")
    else:
        plot_df["HR_lo"] = np.exp(pd.to_numeric(plot_df["coef lower 95%"], errors="coerce"))
        plot_df["HR_hi"] = np.exp(pd.to_numeric(plot_df["coef upper 95%"], errors="coerce"))

    plot_df["p"] = pd.to_numeric(plot_df["p"], errors="coerce")
    plot_df = plot_df.dropna(subset=["HR", "HR_lo", "HR_hi", "p"])
    return plot_df


def _plot_simple_cox_forest(summary_df, title, out_png, style, point_color=None):
    plot_df = _summary_to_hr_frame(summary_df)
    if plot_df.empty:
        return

    _save_hr_table_outputs(summary_df, out_png, title=title)

    plot_df = plot_df.sort_values("HR", ascending=True)
    hr_figsize = style.get("hr_figsize")
    if hr_figsize is None:
        hr_figsize = (8.0, max(3.0, 0.55 * len(plot_df) + 1.0))
    plt.figure(figsize=tuple(hr_figsize))
    ax = plt.gca()

    y = np.arange(len(plot_df))
    hr = plot_df["HR"].to_numpy()
    lo = plot_df["HR_lo"].to_numpy()
    hi = plot_df["HR_hi"].to_numpy()
    xerr = np.vstack([hr - lo, hi - hr])

    color = point_color if point_color else default_palette_color(0)
    ax.errorbar(
        hr,
        y,
        xerr=xerr,
        fmt="o",
        capsize=3,
        color=color,
        ecolor=color,
        markerfacecolor=color,
        markeredgecolor=color,
    )
    ax.axvline(1.0, linestyle="--", linewidth=1.0, color=_element_color("reference", style, DEFAULT_ELEMENT_COLORS["reference"]))
    ax.set_xscale("log")
    ax.set_xlabel("Hazard ratio (log scale)")
    ax.set_yticks(y)
    ax.set_yticklabels(plot_df.index.astype(str).tolist())
    ax.set_title(title)

    stats_df = plot_df.reset_index().rename(columns={'index': 'term'})[[c for c in ['term', 'HR', 'HR_lo', 'HR_hi', 'p'] if c in plot_df.reset_index().rename(columns={'index': 'term'}).columns]]
    _save_stats_csv(out_png, stats_df)
    plt.tight_layout()
    plt.savefig(out_png, dpi=200)
    plt.close()


def _run_prediction_cox_simple(
    out_df,
    labels_map,
    plots_dir,
    preds_dir,
    prefix,
    token,
    style,
    labels_order=None,
    penalizer=0.01,
):
    result = {"continuous_summary": None, "group_summary": None, "binary_summary": None}

    try:
        from lifelines import CoxPHFitter
    except Exception:
        print(f"[{prefix}] lifelines not available; skipping Cox.")
        return result

    if ("time_to_event" not in labels_map) or (("event_observed" not in labels_map) and ("disease_status" not in labels_map)):
        print(f"[{prefix}] Cox skipped (time or event not available).")
        return result

    if "event_observed" in labels_map and labels_map["event_observed"] is not None:
        ev = _to_binary_event_for_survival(labels_map["event_observed"])
    else:
        ev = labels_map["disease_status"].map({"recurrent": 1, "non-recurrent": 0, "nonrecurrent": 0})

    tm = pd.to_numeric(labels_map["time_to_event"], errors="coerce")
    base_df = out_df.set_index("sample_id")[["predicted_proba", "pct_group"]].join(pd.DataFrame({"event": ev, "time": tm}))
    base_df = base_df.dropna(subset=["predicted_proba", "event", "time"]).copy()

    if base_df.empty or base_df["event"].sum() < 3:
        print(f"[{prefix}] Cox skipped: insufficient usable rows/events.")
        return result

    model_col = _model_color(prefix, style)

    try:
        cont_df = base_df[["time", "event", "predicted_proba"]].copy()
        cont_df["predicted_proba_per_0p1"] = cont_df["predicted_proba"] / 0.1
        cont_df = cont_df.drop(columns=["predicted_proba"])

        cph = CoxPHFitter(penalizer=penalizer)
        cph.fit(cont_df, duration_col="time", event_col="event")

        cont_csv = os.path.join(preds_dir, f"{prefix}__cox_continuous__{token}.csv")
        cont_png = os.path.join(plots_dir, f"{prefix}__cox_forest_continuous__{token}.png")
        cont_summary = cph.summary.copy()
        cont_summary['n_used'] = int(cont_df.shape[0])
        cont_summary['n_events'] = int(cont_df['event'].sum())
        cont_summary['unit'] = 'per 0.1 increase in predicted score'
        cont_summary.to_csv(cont_csv)
        _plot_simple_cox_forest(cont_summary, f"[{prefix}] Cox: predicted score (per 0.1)", cont_png, style, point_color=model_col)
        print(f"[PLOT] {cont_png}")
        result["continuous_summary"] = cont_summary.copy()
    except Exception as e:
        print(f"[WARN][{prefix}] Continuous Cox failed: {e}")

    order = labels_order or list(pd.Series(base_df["pct_group"]).dropna().astype(str).unique())
    order = [g for g in order if (base_df["pct_group"].astype(str) == g).any()]

    try:
        grp = pd.Categorical(base_df["pct_group"].astype(str), categories=order, ordered=True)
        grp_dummies = pd.get_dummies(grp, prefix="pct_group", drop_first=True)
        grp_df = pd.concat([base_df[["time", "event"]], grp_dummies], axis=1).dropna()
        grp_terms = [c for c in grp_df.columns if c.startswith("pct_group_")]

        if grp_terms and grp_df["event"].sum() >= 3:
            cph_grp = CoxPHFitter(penalizer=penalizer)
            cph_grp.fit(grp_df, duration_col="time", event_col="event")

            grp_csv = os.path.join(preds_dir, f"{prefix}__cox_groups__{token}.csv")
            grp_png = os.path.join(plots_dir, f"{prefix}__cox_forest_groups__{token}.png")
            grp_summary = cph_grp.summary.copy()
            grp_summary['n_used'] = int(grp_df.shape[0])
            grp_summary['n_events'] = int(grp_df['event'].sum())
            grp_summary['reference_group'] = str(order[0]) if len(order) > 0 else ''
            grp_summary.to_csv(grp_csv)
            _plot_simple_cox_forest(grp_summary, f"[{prefix}] Cox: percentile groups", grp_png, style, point_color=model_col)
            print(f"[PLOT] {grp_png}")
            result["group_summary"] = grp_summary.copy()
    except Exception as e:
        print(f"[WARN][{prefix}] Group Cox failed: {e}")

    try:
        if len(order) >= 2:
            low_group = str(order[0])
            high_group = str(order[-1])
            tb_df = base_df[base_df["pct_group"].astype(str).isin([low_group, high_group])].copy()
            if not tb_df.empty:
                tb_df["is_top_group"] = (tb_df["pct_group"].astype(str) == high_group).astype(int)
                tb_df = tb_df[["time", "event", "is_top_group"]].dropna()
                n_low = int((tb_df["is_top_group"] == 0).sum())
                n_high = int((tb_df["is_top_group"] == 1).sum())
                if n_low > 0 and n_high > 0 and tb_df["event"].sum() >= 3:
                    cph_bin = CoxPHFitter(penalizer=penalizer)
                    cph_bin.fit(tb_df, duration_col="time", event_col="event")

                    bin_summary = cph_bin.summary.copy()
                    bin_summary["comparison_group"] = high_group
                    bin_summary["reference_group"] = low_group
                    bin_summary["comparison_n"] = n_high
                    bin_summary["reference_n"] = n_low
                    bin_summary['n_used'] = int(tb_df.shape[0])
                    bin_summary['n_events'] = int(tb_df['event'].sum())

                    bin_csv = os.path.join(preds_dir, f"{prefix}__cox_binary_top_vs_bottom__{token}.csv")
                    bin_png = os.path.join(plots_dir, f"{prefix}__cox_forest_binary_top_vs_bottom__{token}.png")
                    bin_summary.to_csv(bin_csv)
                    _plot_simple_cox_forest(
                        bin_summary,
                        f"[{prefix}] Cox: top vs bottom ({high_group} vs {low_group})",
                        bin_png,
                        style,
                        point_color=model_col,
                    )
                    _save_stats_figure(
                        bin_png,
                        f"Comparison: {high_group} vs {low_group}\nTop n={n_high}\nBottom n={n_low}",
                        title="Binary Cox top vs bottom",
                    )
                    print(f"[PLOT] {bin_png}")
                    result["binary_summary"] = bin_summary.copy()
                else:
                    print(f"[{prefix}] Binary Cox skipped: need both top and bottom groups with sufficient events.")
            else:
                print(f"[{prefix}] Binary Cox skipped: no rows in top/bottom groups.")
        else:
            print(f"[{prefix}] Binary Cox skipped: need at least two percentile groups.")
    except Exception as e:
        print(f"[WARN][{prefix}] Binary top-vs-bottom Cox failed: {e}")

    return result
