def _format_sig_hr_right_label(hr, lo, hi, p):
    try:
        hr = float(hr)
        lo = float(lo)
        hi = float(hi)
        p = float(p)
    except Exception:
        return ""
    sig = "*" if (not np.isnan(p) and p < 0.05) else "ns"
    if np.isnan(p):
        p_txt = "NA"
    elif p < 1e-16:
        p_txt = "<1e-16"
    else:
        p_txt = f"{p:.2e}"
    return f"{sig}  HR={hr:.2f} ({lo:.2f}-{hi:.2f}), p={p_txt}"

def _plot_hist(
    df,
    score_col_display,
    group_col,
    labels_order,
    title,
    out_png,
    bins,
    style,
    vlines=None,
    info="",
):
    plt.figure(figsize=(7.2, 4.6))
    ax = plt.gca()
    col = df[group_col].astype(str)
    present_labels = [lab for lab in labels_order if (col == lab).any()]
    if not present_labels:
        present_labels = [str(x) for x in pd.Series(col).dropna().unique().tolist()]

    color_map = _group_color_dict(present_labels, style)
    legend_handles = []

    drew_any = False
    for lab in present_labels:
        vals = df.loc[col == lab, score_col_display].astype(float).values
        if len(vals):
            color = color_map[lab]
            ax.hist(vals, bins=bins, alpha=0.6, color=color, edgecolor="none")
            legend_handles.append(Patch(facecolor=color, alpha=0.6, label=lab))
            drew_any = True

    if not drew_any:
        ax.hist(df[score_col_display].astype(float).values, bins=bins, alpha=0.8, color=default_palette_color(0), edgecolor="none")

    ax.set_xlim(0, 1)
    ax.set_xlabel("Score (0–1, display scaling)")
    ax.set_ylabel("Count")
    ax.set_title(title)

    cutline_color = _element_color("cutline", style, DEFAULT_ELEMENT_COLORS["cutline"])
    if vlines:
        for xv in vlines:
            ax.axvline(np.clip(float(xv), 0, 1), linestyle="--", linewidth=1.3, color=cutline_color)

    _save_stats_figure(out_png, info)
    _finalize_legend(ax, legend_handles, [h.get_label() for h in legend_handles], out_png, style, loc="best")
    plt.tight_layout()
    plt.savefig(out_png, dpi=200)
    plt.close()


